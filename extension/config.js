// Строит <select> с <optgroup> для любого select-элемента
function buildTypeSelect(selectEl, selectedValue = '') {
  selectEl.innerHTML = '<option value="">— Характер —</option>';
  TARGET_TYPE_GROUPS.forEach(group => {
    const og = document.createElement('optgroup');
    og.label = group.label;
    group.items.forEach(([id, name]) => {
      const opt = document.createElement('option');
      opt.value = id;
      opt.textContent = name;
      if (id === selectedValue) opt.selected = true;
      og.appendChild(opt);
    });
    selectEl.appendChild(og);
  });
}

